const (
	// rustModelsDir is the directory generators write their output to, which
	// the schema manager strips when it copies them into the project.
	rustModelsDir = "models"

	// rustSrcDir is the crate's source directory, relative to the crate root.
	rustSrcDir = "src"

	// rustGeneratedHeader marks every file we emit. It matches the convention
	// Go tooling recognizes, which several editors and linters reuse.
	rustGeneratedHeader = "// Code generated by github.com/crossplane/cli/v2 DO NOT EDIT."

	// rustMaxDepth caps how deep we walk into inline objects. Structural
	// schemas are finite trees, so this only guards against pathological input
	// taking the whole CLI down with a stack overflow. rustc gives up on types
	// nested about this deep anyway; the limit is here so that the generator's
	// own behavior is explicit rather than left to the size of the Go stack.
	rustMaxDepth = 64

	// rustSharedPackage prefixes the component schemas that both generation
	// flows emit, see rustPrepareSchemas.
	rustSharedPackage = "io.k8s.apimachinery."

	// rustAdditionalProperties is the JSON-side name of the field that keeps
	// the properties a schema allows without naming them.
	rustAdditionalProperties = "additionalProperties"

	// rustPreserveUnknownFields marks an object whose unknown fields the API
	// server keeps.
	rustPreserveUnknownFields = "x-kubernetes-preserve-unknown-fields"
)

